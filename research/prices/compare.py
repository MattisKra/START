"""Score each price source against the known t bounds of the old cases.

hit      : p satisfies the bound (p >= lo, p < hi)
distance : |log(p / bound)| for a miss, 0 for a hit
coverage : test lines and distinct cases the source prices (plan rule: >= 3 cases)

Writes research/prices/report.md and prints the ranking.
Run: python3 -I research/prices/compare.py   (after match.py)
"""
import json
import math
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent


def score(p, lo, hi):
    if lo is not None and p < lo:
        return False, math.log(lo / p)
    if hi is not None and p >= hi:
        return False, math.log(p / hi)
    return True, 0.0


def bound_str(l):
    if l["lo"] is not None and l["hi"] is not None:
        return f"[{l['lo']:.0f}, {l['hi']:.0f})"
    return f"≥ {l['lo']:.0f}" if l["lo"] is not None else f"< {l['hi']:.0f}"


def main():
    test = {l["id"]: l for l in json.loads((HERE / "testset.json").read_text())["lines"]}
    m = json.loads((HERE / "matches.json").read_text())
    res = {}
    for x in m["matches"]:
        l = test[x["line"]]
        hit, d = score(x["p"], l["lo"], l["hi"])
        res.setdefault(x["source"], {"family": x["family"], "lines": {}})["lines"][x["line"]] = (x["p"], hit, d, x)

    rank = []
    for src, r in res.items():
        ls = r["lines"]
        cases = sorted({test[i]["case"] for i in ls})
        hits = sum(v[1] for v in ls.values())
        dists = [v[2] for v in ls.values()]
        two_sided = [i for i in ls if test[i]["lo"] is not None and test[i]["hi"] is not None]
        rank.append({
            "source": src, "family": r["family"], "lines": len(ls), "cases": len(cases), "case_ids": cases,
            "hits": hits, "hit_rate": hits / len(ls), "median_dist": statistics.median(dists),
            "mean_dist": sum(dists) / len(dists), "eligible": len(cases) >= 3, "two_sided": len(two_sided),
        })
    rank.sort(key=lambda r: (not r["eligible"], -r["hit_rate"], r["median_dist"], -r["lines"]))

    out = ["# Price sources vs. known t bounds of the old cases", "",
           "Generated by `research/prices/compare.py`; inputs `testset.json`, `prices.csv`, `matches.json`.", "",
           "## Ranking", "",
           "| # | source | family | lines | cases | hits | hit rate | median dist | mean dist | ≥3 cases |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rank, 1):
        out.append(f"| {i} | {r['source']} | {r['family']} | {r['lines']} | {r['cases']} ({', '.join(map(str, r['case_ids']))}) | "
                   f"{r['hits']} | {r['hit_rate']:.0%} | {r['median_dist']:.2f} | {r['mean_dist']:.2f} | {'yes' if r['eligible'] else 'no'} |")
    out += ["", "Distance = |ln(p / bound)| for a miss (0.69 = off by a factor 2). Most bounds are one-sided: a source that",
            "prices too high always 'hits' a ≥ bound, a source that prices too low always hits a < bound. Only case 1 line 1",
            "has a two-sided bracket. Read the per-line table, not only the hit rate.", ""]

    srcs = [r["source"] for r in rank]
    out += ["## Per line (p in EUR gross, ✓ = inside the bound)", "",
            "| line | text | t bound | " + " | ".join(srcs) + " |", "|---|---|---|" + "---|" * len(srcs)]
    for lid, l in test.items():
        cells = []
        for s in srcs:
            v = res[s]["lines"].get(lid)
            cells.append("" if not v else f"{v[0]:.0f} {'✓' if v[1] else '✗'}")
        out.append(f"| {lid} | {l['text'][:48]} | {bound_str(l)} | " + " | ".join(cells) + " |")

    out += ["", "## Assumptions not taken from any source", "", "```json", json.dumps(m["assume"], indent=1), "```", "",
            "## Match details", ""]
    for s in srcs:
        out.append(f"### {s}")
        for lid, (p, hit, d, x) in res[s]["lines"].items():
            parts = "; ".join(f"{pt['tag']} {pt['stat']} {pt['value']:.0f}×{pt['qty']:g} (n={pt['n']}, IQR {pt['p25']:.0f}–{pt['p75']:.0f}"
                              f"{', regional' if pt['regional'] else ''}, e.g. “{pt['example']['item'][:60]}” {pt['example']['unit']})"
                              for pt in x["parts"])
            implied = ""
            if res[s]["family"] == "rates":  # assumption-free view: hours the bound needs at this rate
                rate = x["parts"][0]["value"]
                travel = sum(pt["value"] for pt in x["parts"][1:])
                l = test[lid]
                if l["lo"] is not None:
                    implied = f" Bound needs ≥ {(l['lo'] - travel) / rate:.1f} h at this rate."
                else:
                    implied = f" Bound allows < {(l['hi'] - travel) / rate:.1f} h at this rate."
            out.append(f"- {lid}: p={p:.0f} vs {bound_str(test[lid])} → {'hit' if hit else f'miss, dist {d:.2f}'}. {parts}.{implied}")
        out.append("")
    (HERE / "report.md").write_text("\n".join(out), encoding="utf-8")
    for r in rank:
        print(f"{r['source']:<22} lines={r['lines']:>2} cases={r['cases']:>2} hit={r['hit_rate']:.0%} "
              f"med_dist={r['median_dist']:.2f} {'OK' if r['eligible'] else '<3 cases'}")
    print("-> research/prices/report.md")


if __name__ == "__main__":
    main()
