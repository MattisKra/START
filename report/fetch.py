"""Refresh report data from the PUBLIC leaderboard (one request) and write numbers.tex for the report.

    python3 -I report/fetch.py            # then: uv run --no-project --with matplotlib python -I report/plots.py

Only our own per-game net and anonymous field aggregates (median, quartiles, best other team) are stored. No team names.
"""
import json, os, statistics as st, urllib.request

os.chdir(os.path.dirname(os.path.abspath(__file__)))
US, FABLE_FROM = "Kiebler Software Solutions", 22  # first game played by the Fable /loop agent (team timeline)
req = urllib.request.Request("https://c2f.public.quantco.cloud/leaderboard/api/matrix?page=1&game_limit=200",
                             headers={"User-Agent": "team-analysis/1.0"})
m = json.load(urllib.request.urlopen(req, timeout=30))
ids = m["game_ids"]
rows = {it["team_name"]: [x or 0 for x in it["cells"]] for it in m["items"]}
order = sorted(range(len(ids)), key=lambda i: ids[i])
oth = lambda i: [rows[k][i] for k in rows if k != US]
d = {"game_ids": [ids[i] for i in order], "ours": [rows[US][i] for i in order], "n_teams": len(rows),
     "field_median_game": [st.median(oth(i)) for i in order],
     "field_q25_game": [st.quantiles(oth(i), n=4)[0] for i in order],
     "field_q75_game": [st.quantiles(oth(i), n=4)[2] for i in order],
     "best_other_game": [max(oth(i)) for i in order],
     "game_rank": [sorted([rows[k][i] for k in rows], reverse=True).index(rows[US][i]) + 1 for i in order]}
cum = {k: 0 for k in rows}; rk, fm, bo = [], [], []
for i in order:
    for k in rows:
        cum[k] += rows[k][i]
    rk.append(sorted(cum.values(), reverse=True).index(cum[US]) + 1)
    o = [cum[k] for k in rows if k != US]; fm.append(st.median(o)); bo.append(max(o))
d.update(rank=rk, field_median_cum=fm, field_best_other_cum=bo)
json.dump(d, open("standing_anon.json", "w"))

o, gr, n = d["ours"], d["game_rank"], len(d["ours"])
pre, post = slice(0, FABLE_FROM - 1), slice(FABLE_FROM - 1, n)
c, lead = 0, []
for i in range(n):
    c += o[i]; lead.append(c - bo[i])
k = lambda v: f"{v / 1e3:,.0f}k"
pct = lambda xs, f: round(100 * sum(map(f, xs)) / len(xs))
nums = {
    "FableFrom": FABLE_FROM, "PreLast": FABLE_FROM - 1,
    "NGames": n, "NTeams": len(rows), "Rank": rk[-1], "Total": k(c), "BestOther": k(bo[-1]), "Lead": k(lead[-1]),
    "WorstRank": max(rk), "WorstRankGame": rk.index(max(rk)) + 1,
    "MinLead": k(-min(lead)), "MinLeadGame": lead.index(min(lead)) + 1,
    "RankOneSince": max((i for i in range(n) if rk[i] != 1), default=-1) + 2,
    "PreNet": k(sum(o[pre])), "PreMean": f"{st.mean(o[pre]) / 1e3:.1f}k", "PostMean": f"{st.mean(o[post]) / 1e3:.1f}k",
    "PreWin": pct(o[pre], lambda x: x > 0), "PostWin": pct(o[post], lambda x: x > 0),
    "PreTop": pct(gr[pre], lambda x: x <= 3), "PostTop": pct(gr[post], lambda x: x <= 3),
    "PostLosses": sum(x < 0 for x in o[post]), "PostGames": n - FABLE_FROM + 1,
}
with open("numbers.tex", "w") as f:
    f.write("% generated by fetch.py, do not edit\n")
    for key, v in nums.items():
        f.write(f"\\newcommand{{\\{key}}}{{{str(v).replace('-', '$-$') if isinstance(v, str) else v}}}\n")
print(nums)
